/**
 * EEPROM of an AM32 2.22 ESC (layout 4, 192 bytes) as the firmware keeps it:
 * every byte different from its neighbours, so that a byte out of place shows.
 */
function layout4Image() {
  const image = new Uint8Array(0xC0);
  image.set([
    0x01, 0x04, 0x0C, 0x02, 0x16, // boot byte, layout 4, bootloader, 2.22
    0xA0, 0x04, 0x00, 0x0A, 0x64, 0x01, 0x32, 0x02, 0x02, 0x03, // 5-14
    0x5A, 0xA5, // 15-16 reserved
    0x00, 0x00, 0x00, 0x01, 0x01, 0x01, 0x1A, 0x18, 0x64, 0x37, 0x0E, 0x02, 0x00, 0x05, 0x00, // 17-31
    0x80, 0x81, 0x82, 0x32, // 32-35 servo
    0x00, 0x32, 0x00, 0x00, 0x0F, 0x0A, 0x0A, 0xFF, 0x00, 0x06, 0x00, 0x01, // 36-47
  ]);
  for(let i = 0x30; i < 0xB0; i += 1) {
    image[i] = (i * 7) & 0xFF;
  }
  image.set([0x05, 0x02, 0x01, 0x19, 0x01, 0x00, 0x00, 0x01], 0xB0);
  image.set([0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88], 0xB8);

  return image;
}

export default layout4Image;
